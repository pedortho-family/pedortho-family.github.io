"""Builds js/icons.js: the site's line icons as one inline SVG sprite.

Icons are Lucide (ISC licence), pinned to lucide-static 0.460.0 so every icon
matches. To add one: append its Lucide name to NAMES and run
    python3 tools/icons/build_icons.py
then use it in markup as icon('name') (app.js) or
<svg class="ic"><use href="#i-name"/></svg> (index.html).
"""
import os
import re
import subprocess
import tempfile

VERSION = '0.460.0'
NAMES = """
menu search share-2 x house layout-grid clipboard-list qr-code arrow-up chevron-left
chevron-right chevron-down message-circle link-2 copy check printer download lock bone
heart-handshake brain footprints activity stethoscope book-open dna scan-search pill scissors
bed dumbbell siren circle-help clock list-checks circle-check citrus triangle-alert file-text
shapes layers sun baby accessibility house-plus bandage refresh-cw list play info lightbulb
calendar target images send mail heart-pulse shield-check hand-heart
""".split()

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def fetch(name, folder):
    path = os.path.join(folder, name + '.svg')
    url = f'https://unpkg.com/lucide-static@{VERSION}/icons/{name}.svg'
    code = subprocess.run(['curl', '-sL', '-o', path, '-w', '%{http_code}', url],
                          capture_output=True, text=True).stdout
    if code != '200':
        raise SystemExit(f'Lucide has no icon called "{name}" ({url})')
    return open(path).read()


def main():
    symbols = []
    with tempfile.TemporaryDirectory() as tmp:
        for name in NAMES:
            body = re.search(r'<svg[^>]*>(.*)</svg>', fetch(name, tmp), re.S).group(1)
            body = re.sub(r'\s*\n\s*', '', body)
            symbols.append(f'<symbol id="i-{name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">{body}</symbol>')
    sprite = ''.join(symbols)
    js = f"""/* Line icons for the whole site, one inline SVG sprite (Lucide {VERSION}, ISC licence).
   Generated by tools/icons/build_icons.py; edit the list there, not this file.
   Stroke width comes from CSS (.ic), so a page can draw an icon finer or bolder. */
(function () {{
    'use strict';
    const SPRITE = '{sprite}';
    const holder = document.createElement('div');
    holder.innerHTML = '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="position:absolute;width:0;height:0;overflow:hidden">' + SPRITE + '</svg>';
    const insert = () => document.body.insertBefore(holder.firstChild, document.body.firstChild);
    if (document.body) insert(); else document.addEventListener('DOMContentLoaded', insert);

    // Markup for one icon: icon('house') or icon('house', 'nav-ic').
    window.icon = function (name, cls) {{
        return '<svg class="ic' + (cls ? ' ' + cls : '') + '" aria-hidden="true"><use href="#i-' + name + '"/></svg>';
    }};
}})();
"""
    open(os.path.join(ROOT, 'js', 'icons.js'), 'w').write(js)
    print(f'js/icons.js: {len(NAMES)} icons, {len(js) // 1024} KB')


if __name__ == '__main__':
    main()
